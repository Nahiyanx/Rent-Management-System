<?php

namespace App\Support;

use App\Models\Expense;
use App\Models\RentPayment;
use Dompdf\Dompdf;
use Dompdf\Options;
use Illuminate\Support\Carbon;
use Illuminate\Support\Collection;
use PhpOffice\PhpSpreadsheet\Shared\Date;
use PhpOffice\PhpSpreadsheet\Spreadsheet;
use PhpOffice\PhpSpreadsheet\Style\Alignment;
use PhpOffice\PhpSpreadsheet\Style\Border;
use PhpOffice\PhpSpreadsheet\Style\Fill;
use PhpOffice\PhpSpreadsheet\Worksheet\PageSetup;
use PhpOffice\PhpSpreadsheet\Worksheet\Worksheet;
use PhpOffice\PhpSpreadsheet\Writer\Xlsx;

/**
 * Builds the monthly Cashbook PDF and Excel workbook from the same data.
 *
 * Every figure comes from Financials::summary() so the exports always match the
 * Dashboard and Cashbook. The PDF and workbook are presentation-only layers.
 */
final class CashbookReport
{
    private const MONEY_FORMAT = '"BDT "#,##0.00;[Red]-"BDT "#,##0.00';

    private const DATE_FORMAT = 'dd mmm yyyy';

    private const ESPRESSO = 'FF200E01';

    private const BURGUNDY = 'FF5B0202';

    private const WINE = 'FF8B0000';

    private const CREAM = 'FFEDE7C7';

    private const PARCHMENT = 'FFF6F0D8';

    private const HAIRLINE = 'FFE1D8AE';

    /**
     * @return array{
     *     month: string,
     *     month_label: string,
     *     summary: array<string, mixed>,
     *     expenses: Collection<int, Expense>,
     *     receipts: Collection<int, RentPayment>
     * }
     */
    public static function data(string $month): array
    {
        $start = Carbon::createFromFormat('Y-m', $month)->startOfMonth();
        $end = $start->copy()->endOfMonth();

        $receipts = RentPayment::query()
            ->whereBetween('paid_on', [$start->toDateString(), $end->toDateString()])
            ->with([
                'rentBill.tenancy.tenant',
                'rentBill.tenancy.flat.building',
            ])
            ->orderBy('paid_on')
            ->orderBy('id')
            ->get();

        return [
            'month' => $month,
            'month_label' => $start->format('F Y'),
            'summary' => Financials::summary($month),
            'expenses' => Financials::expensesForMonth($month),
            'receipts' => $receipts,
        ];
    }

    public static function html(string $month): string
    {
        return view('reports.cashbook-pdf', [
            'report' => self::data($month),
        ])->render();
    }

    public static function pdf(string $month): string
    {
        $options = new Options;
        $options->set('defaultFont', 'DejaVu Sans');
        $options->set('isHtml5ParserEnabled', true);
        $options->set('isRemoteEnabled', false);
        $options->set('chroot', base_path());

        $dompdf = new Dompdf($options);
        $dompdf->loadHtml(self::html($month), 'UTF-8');
        $dompdf->setPaper('A4', 'portrait');
        $dompdf->render();

        $canvas = $dompdf->getCanvas();
        $canvas->page_text(
            34,
            $canvas->get_height() - 24,
            'Rentra · Monthly Cashbook · Page {PAGE_NUM} of {PAGE_COUNT}',
            'Helvetica',
            8,
            [0.42, 0.36, 0.27],
        );

        return $dompdf->output();
    }

    public static function xlsxPath(string $month): string
    {
        $spreadsheet = self::workbook(self::data($month));

        $writer = new Xlsx($spreadsheet);
        $writer->setPreCalculateFormulas(true);

        $path = tempnam(sys_get_temp_dir(), 'rentra-cashbook-');

        if ($path === false) {
            throw new \RuntimeException('Unable to create a temporary workbook file.');
        }

        $writer->save($path);

        return $path;
    }

    public static function xlsxBinary(string $month): string
    {
        $path = self::xlsxPath($month);

        try {
            return (string) file_get_contents($path);
        } finally {
            @unlink($path);
        }
    }

    public static function filename(string $month, string $extension): string
    {
        return 'rentra-cashbook-'.$month.'.'.$extension;
    }

    /**
     * @param  array<string, mixed>  $report
     */
    private static function workbook(array $report): Spreadsheet
    {
        $spreadsheet = new Spreadsheet;
        $spreadsheet->getProperties()
            ->setCreator('Rentra')
            ->setLastModifiedBy('Rentra')
            ->setTitle('Monthly Cashbook '.$report['month_label'])
            ->setDescription('Monthly cashbook report generated by Rentra.');

        $spreadsheet->getDefaultStyle()
            ->getFont()
            ->setName('Calibri')
            ->setSize(10);

        $summarySheet = $spreadsheet->getActiveSheet();
        $summarySheet->setTitle('Financial Summary');
        self::buildSummarySheet($summarySheet, $report);

        $receiptsSheet = $spreadsheet->createSheet();
        $receiptsSheet->setTitle('Rent Receipts');
        self::buildReceiptsSheet($receiptsSheet, $report);

        $expensesSheet = $spreadsheet->createSheet();
        $expensesSheet->setTitle('Expenses');
        self::buildExpensesSheet($expensesSheet, $report);

        $spreadsheet->setActiveSheetIndex(0);

        return $spreadsheet;
    }

    /**
     * @param  array<string, mixed>  $report
     */
    private static function buildSummarySheet(Worksheet $sheet, array $report): void
    {
        /** @var array<string, mixed> $summary */
        $summary = $report['summary'];

        $sheet->setShowGridLines(false);
        $sheet->mergeCells('A1:D1');
        $sheet->setCellValue('A1', 'RENTRA');
        $sheet->getStyle('A1')->getFont()
            ->setBold(true)
            ->setSize(20)
            ->getColor()->setARGB(self::ESPRESSO);
        $sheet->getRowDimension(1)->setRowHeight(30);

        $sheet->mergeCells('A2:D2');
        $sheet->setCellValue('A2', 'Monthly Cashbook');
        $sheet->getStyle('A2')->getFont()
            ->setBold(true)
            ->setSize(14)
            ->getColor()->setARGB(self::BURGUNDY);

        $sheet->mergeCells('A3:D3');
        $sheet->setCellValue('A3', 'Financial summary · '.$report['month_label']);
        $sheet->getStyle('A3')->getFont()
            ->setSize(10)
            ->setItalic(true)
            ->getColor()->setARGB('FF6B5B4A');

        $headers = ['Item', 'Cash', 'Bank', 'Combined'];
        $sheet->fromArray($headers, null, 'A5');
        self::styleHeaderRow($sheet, 'A5:D5');

        $rows = [
            ['Cash opening balance', $summary['starting_cash'], null, null],
            ['Bank opening balance', null, $summary['starting_bank'], null],
            [
                'Rent received',
                '=SUMIFS(\'Rent Receipts\'!$G:$G,\'Rent Receipts\'!$F:$F,"Cash")',
                '=SUMIFS(\'Rent Receipts\'!$H:$H,\'Rent Receipts\'!$F:$F,"Bank")',
                '=B8+C8',
            ],
            [
                'Cash expenses',
                '=SUMIFS(Expenses!$D:$D,Expenses!$C:$C,"Cash")',
                null,
                null,
            ],
            [
                'Bank expenses',
                null,
                '=SUMIFS(Expenses!$E:$E,Expenses!$C:$C,"Bank")',
                null,
            ],
            ['Cash closing balance', '=B6+B8-B9', null, null],
            ['Bank closing balance', null, '=C7+C8-C10', null],
            ['Combined closing balance', null, null, '=B11+C12'],
        ];

        $sheet->fromArray($rows, null, 'A6');

        $sheet->getStyle('A6:A13')->getFont()->setBold(false);
        $sheet->getStyle('A6:A13')->getAlignment()->setVertical(Alignment::VERTICAL_CENTER);
        $sheet->getStyle('B6:D13')->getAlignment()->setHorizontal(Alignment::HORIZONTAL_RIGHT);
        $sheet->getStyle('B6:D13')->getNumberFormat()->setFormatCode(self::MONEY_FORMAT);

        foreach (['B6', 'C7', 'B8', 'C8', 'D8', 'B9', 'C10', 'B11', 'C12', 'D13'] as $cell) {
            $sheet->getStyle($cell)->getFont()->setBold(true);
        }

        $sheet->getStyle('A11:D13')->getFill()
            ->setFillType(Fill::FILL_SOLID)
            ->getStartColor()->setARGB('FFF8F4E3');
        $sheet->getStyle('A13:D13')->getBorders()->getTop()
            ->setBorderStyle(Border::BORDER_MEDIUM)
            ->getColor()->setARGB(self::WINE);
        $sheet->getStyle('D13')->getFont()->setSize(12)->getColor()->setARGB(self::WINE);

        foreach (['A6:D6', 'A7:D7', 'A8:D8', 'A9:D9', 'A10:D10', 'A11:D11', 'A12:D12', 'A13:D13'] as $range) {
            $sheet->getStyle($range)->getBorders()->getBottom()
                ->setBorderStyle(Border::BORDER_HAIR)
                ->getColor()->setARGB(self::HAIRLINE);
        }

        $sheet->mergeCells('A15:D15');
        $sheet->setCellValue(
            'A15',
            'Opening balances are not rental income. Rent is recognised on its actual payment date; expenses on their expense date.',
        );
        $sheet->getStyle('A15')->getFont()
            ->setSize(9)
            ->setItalic(true)
            ->getColor()->setARGB('FF6B5B4A');
        $sheet->getStyle('A15')->getAlignment()->setWrapText(true);
        $sheet->getRowDimension(15)->setRowHeight(28);

        $sheet->mergeCells('A17:D17');
        $sheet->setCellValue(
            'A17',
            'Generated by Rentra on '.now()->format('d M Y, H:i').'. Amounts are in Bangladeshi Taka (BDT).',
        );
        $sheet->getStyle('A17')->getFont()
            ->setSize(9)
            ->getColor()->setARGB('FF8A7A68');

        self::setColumnWidths($sheet, ['A' => 31, 'B' => 18, 'C' => 18, 'D' => 20]);
        $sheet->freezePane('A6');
        $sheet->setSelectedCell('A1');
        self::configurePrint($sheet, 'A1:D17', true);
    }

    /**
     * @param  array<string, mixed>  $report
     */
    private static function buildReceiptsSheet(Worksheet $sheet, array $report): void
    {
        /** @var Collection<int, RentPayment> $receipts */
        $receipts = $report['receipts'];

        $sheet->setShowGridLines(false);
        $sheet->mergeCells('A1:H1');
        $sheet->setCellValue('A1', 'Rent Receipts');
        $sheet->getStyle('A1')->getFont()
            ->setBold(true)
            ->setSize(18)
            ->getColor()->setARGB(self::ESPRESSO);
        $sheet->getRowDimension(1)->setRowHeight(28);

        $sheet->mergeCells('A2:H2');
        $sheet->setCellValue('A2', $report['month_label'].' · cash and bank collections');
        $sheet->getStyle('A2')->getFont()
            ->setSize(10)
            ->setItalic(true)
            ->getColor()->setARGB('FF6B5B4A');

        $headers = ['Date', 'Tenant', 'Building', 'Flat', 'Billed for', 'Method', 'Cash', 'Bank'];
        $sheet->fromArray($headers, null, 'A4');
        self::styleHeaderRow($sheet, 'A4:H4');

        $row = 5;

        foreach ($receipts as $payment) {
            $tenancy = $payment->rentBill?->tenancy;
            $amount = (float) $payment->amount;

            $sheet->setCellValue('A'.$row, Date::PHPToExcel($payment->paid_on->copy()->startOfDay()));
            $sheet->setCellValue('B'.$row, $tenancy?->tenant?->name ?? '—');
            $sheet->setCellValue('C'.$row, $tenancy?->flat?->building?->name ?? '—');
            $sheet->setCellValue('D'.$row, $tenancy?->flat?->unit_number ?? '—');
            $sheet->setCellValue(
                'E'.$row,
                $payment->rentBill?->billing_month
                    ? Carbon::createFromFormat('Y-m', $payment->rentBill->billing_month)->format('M Y')
                    : '—',
            );
            $sheet->setCellValue('F'.$row, $payment->method);
            $sheet->setCellValue('G'.$row, $payment->method === 'Cash' ? $amount : 0);
            $sheet->setCellValue('H'.$row, $payment->method === 'Bank' ? $amount : 0);

            $sheet->getStyle('A'.$row)->getNumberFormat()->setFormatCode(self::DATE_FORMAT);
            $sheet->getStyle('G'.$row.':H'.$row)->getNumberFormat()->setFormatCode(self::MONEY_FORMAT);
            self::styleDataRow($sheet, 'A'.$row.':H'.$row, $row);

            $row++;
        }

        if ($receipts->isEmpty()) {
            $sheet->mergeCells('A5:H5');
            $sheet->setCellValue('A5', 'No rent receipts were recorded for this month.');
            $sheet->getStyle('A5')->getFont()->setItalic(true)->getColor()->setARGB('FF8A7A68');
            $sheet->getStyle('A5')->getAlignment()->setHorizontal(Alignment::HORIZONTAL_CENTER);
            $row = 6;
        }

        $totalRow = $row;
        $sheet->mergeCells('A'.$totalRow.':F'.$totalRow);
        $sheet->setCellValue('A'.$totalRow, 'Total rent received');
        $sheet->setCellValue('G'.$totalRow, '=SUM(G5:G'.($totalRow - 1).')');
        $sheet->setCellValue('H'.$totalRow, '=SUM(H5:H'.($totalRow - 1).')');
        $sheet->getStyle('A'.$totalRow.':H'.$totalRow)->getFont()->setBold(true);
        $sheet->getStyle('A'.$totalRow.':H'.$totalRow)->getFill()
            ->setFillType(Fill::FILL_SOLID)
            ->getStartColor()->setARGB('FFF8F4E3');
        $sheet->getStyle('A'.$totalRow.':H'.$totalRow)->getBorders()->getTop()
            ->setBorderStyle(Border::BORDER_MEDIUM)
            ->getColor()->setARGB(self::WINE);
        $sheet->getStyle('G'.$totalRow.':H'.$totalRow)->getNumberFormat()->setFormatCode(self::MONEY_FORMAT);

        $sheet->getStyle('A5:H'.max(5, $totalRow))->getAlignment()->setVertical(Alignment::VERTICAL_CENTER);
        $sheet->getStyle('G5:H'.$totalRow)->getAlignment()->setHorizontal(Alignment::HORIZONTAL_RIGHT);
        self::setColumnWidths($sheet, [
            'A' => 14,
            'B' => 24,
            'C' => 24,
            'D' => 9,
            'E' => 12,
            'F' => 11,
            'G' => 16,
            'H' => 16,
        ]);
        $sheet->freezePane('A5');
        $sheet->setAutoFilter('A4:H'.max(4, $totalRow - 1));
        self::configurePrint($sheet, 'A1:H'.$totalRow, false);
    }

    /**
     * @param  array<string, mixed>  $report
     */
    private static function buildExpensesSheet(Worksheet $sheet, array $report): void
    {
        /** @var Collection<int, Expense> $expenses */
        $expenses = $report['expenses'];

        $sheet->setShowGridLines(false);
        $sheet->mergeCells('A1:F1');
        $sheet->setCellValue('A1', 'Expenses');
        $sheet->getStyle('A1')->getFont()
            ->setBold(true)
            ->setSize(18)
            ->getColor()->setARGB(self::ESPRESSO);
        $sheet->getRowDimension(1)->setRowHeight(28);

        $sheet->mergeCells('A2:F2');
        $sheet->setCellValue('A2', $report['month_label'].' · cash and bank expenses');
        $sheet->getStyle('A2')->getFont()
            ->setSize(10)
            ->setItalic(true)
            ->getColor()->setARGB('FF6B5B4A');

        $headers = ['Date', 'Description', 'Paid from', 'Cash', 'Bank', 'Amount'];
        $sheet->fromArray($headers, null, 'A4');
        self::styleHeaderRow($sheet, 'A4:F4');

        $row = 5;

        foreach ($expenses as $expense) {
            $amount = (float) $expense->amount;

            $sheet->setCellValue('A'.$row, Date::PHPToExcel($expense->expense_date->copy()->startOfDay()));
            $sheet->setCellValue('B'.$row, $expense->description);
            $sheet->setCellValue('C'.$row, $expense->paid_from);
            $sheet->setCellValue('D'.$row, $expense->paid_from === 'Cash' ? $amount : 0);
            $sheet->setCellValue('E'.$row, $expense->paid_from === 'Bank' ? $amount : 0);
            $sheet->setCellValue('F'.$row, '=D'.$row.'+E'.$row);

            $sheet->getStyle('A'.$row)->getNumberFormat()->setFormatCode(self::DATE_FORMAT);
            $sheet->getStyle('D'.$row.':F'.$row)->getNumberFormat()->setFormatCode(self::MONEY_FORMAT);
            self::styleDataRow($sheet, 'A'.$row.':F'.$row, $row);

            $row++;
        }

        if ($expenses->isEmpty()) {
            $sheet->mergeCells('A5:F5');
            $sheet->setCellValue('A5', 'No expenses were recorded for this month.');
            $sheet->getStyle('A5')->getFont()->setItalic(true)->getColor()->setARGB('FF8A7A68');
            $sheet->getStyle('A5')->getAlignment()->setHorizontal(Alignment::HORIZONTAL_CENTER);
            $row = 6;
        }

        $cashRow = $row;
        $sheet->mergeCells('A'.$cashRow.':C'.$cashRow);
        $sheet->setCellValue('A'.$cashRow, 'Cash expenses subtotal');
        $sheet->setCellValue('D'.$cashRow, '=SUM(D5:D'.($cashRow - 1).')');

        $bankRow = $cashRow + 1;
        $sheet->mergeCells('A'.$bankRow.':C'.$bankRow);
        $sheet->setCellValue('A'.$bankRow, 'Bank expenses subtotal');
        $sheet->setCellValue('E'.$bankRow, '=SUM(E5:E'.($bankRow - 1).')');

        $totalRow = $bankRow + 1;
        $sheet->mergeCells('A'.$totalRow.':C'.$totalRow);
        $sheet->setCellValue('A'.$totalRow, 'Total expenses');
        $sheet->setCellValue('F'.$totalRow, '=SUM(F5:F'.($totalRow - 1).')');

        foreach ([$cashRow, $bankRow] as $subtotalRow) {
            $sheet->getStyle('A'.$subtotalRow.':F'.$subtotalRow)->getFont()->setBold(true);
            $sheet->getStyle('D'.$subtotalRow.':F'.$subtotalRow)->getNumberFormat()->setFormatCode(self::MONEY_FORMAT);
            $sheet->getStyle('A'.$subtotalRow.':F'.$subtotalRow)->getBorders()->getTop()
                ->setBorderStyle(Border::BORDER_HAIR)
                ->getColor()->setARGB(self::HAIRLINE);
        }

        $sheet->getStyle('A'.$totalRow.':F'.$totalRow)->getFont()->setBold(true);
        $sheet->getStyle('A'.$totalRow.':F'.$totalRow)->getFill()
            ->setFillType(Fill::FILL_SOLID)
            ->getStartColor()->setARGB('FFF8F4E3');
        $sheet->getStyle('A'.$totalRow.':F'.$totalRow)->getBorders()->getTop()
            ->setBorderStyle(Border::BORDER_MEDIUM)
            ->getColor()->setARGB(self::WINE);
        $sheet->getStyle('F'.$totalRow)->getNumberFormat()->setFormatCode(self::MONEY_FORMAT);

        $sheet->getStyle('A5:F'.$totalRow)->getAlignment()->setVertical(Alignment::VERTICAL_CENTER);
        $sheet->getStyle('D5:F'.$totalRow)->getAlignment()->setHorizontal(Alignment::HORIZONTAL_RIGHT);
        self::setColumnWidths($sheet, [
            'A' => 14,
            'B' => 36,
            'C' => 12,
            'D' => 16,
            'E' => 16,
            'F' => 16,
        ]);
        $sheet->freezePane('A5');
        $sheet->setAutoFilter('A4:F'.max(4, $totalRow - 1));
        self::configurePrint($sheet, 'A1:F'.$totalRow, false);
    }

    private static function styleHeaderRow(Worksheet $sheet, string $range): void
    {
        $sheet->getStyle($range)->getFont()
            ->setBold(true)
            ->setSize(10)
            ->getColor()->setARGB(self::CREAM);
        $sheet->getStyle($range)->getFill()
            ->setFillType(Fill::FILL_SOLID)
            ->getStartColor()->setARGB(self::BURGUNDY);
        $sheet->getStyle($range)->getAlignment()
            ->setHorizontal(Alignment::HORIZONTAL_LEFT)
            ->setVertical(Alignment::VERTICAL_CENTER);
        $sheet->getStyle($range)->getBorders()->getBottom()
            ->setBorderStyle(Border::BORDER_MEDIUM)
            ->getColor()->setARGB(self::WINE);
        $sheet->getRowDimension((int) substr($range, 1, 1))->setRowHeight(22);
    }

    private static function styleDataRow(Worksheet $sheet, string $range, int $row): void
    {
        $sheet->getStyle($range)->getBorders()->getBottom()
            ->setBorderStyle(Border::BORDER_HAIR)
            ->getColor()->setARGB(self::HAIRLINE);

        if ($row % 2 === 0) {
            $sheet->getStyle($range)->getFill()
                ->setFillType(Fill::FILL_SOLID)
                ->getStartColor()->setARGB('FFFAF7EA');
        }
    }

    /**
     * @param  array<string, int>  $widths
     */
    private static function setColumnWidths(Worksheet $sheet, array $widths): void
    {
        foreach ($widths as $column => $width) {
            $sheet->getColumnDimension($column)->setWidth($width);
        }
    }

    private static function configurePrint(Worksheet $sheet, string $area, bool $portrait): void
    {
        $sheet->getPageSetup()
            ->setOrientation($portrait ? PageSetup::ORIENTATION_PORTRAIT : PageSetup::ORIENTATION_LANDSCAPE)
            ->setPaperSize(PageSetup::PAPERSIZE_A4)
            ->setFitToWidth(1)
            ->setFitToHeight(0);
        $sheet->getPageSetup()->setPrintArea($area);
        $sheet->getPageMargins()
            ->setTop(0.5)
            ->setBottom(0.5)
            ->setLeft(0.45)
            ->setRight(0.45);
    }
}
